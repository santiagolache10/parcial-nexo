CREATE TABLE IF NOT EXISTS parcial_julian.practicas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 estudiante_id BIGINT NOT NULL REFERENCES parcial_julian.usuarios(id),
 tutor_id BIGINT REFERENCES parcial_julian.usuarios(id),
 empresa VARCHAR(180) NOT NULL,
 area VARCHAR(130) NOT NULL,
 supervisor VARCHAR(160),
 contacto VARCHAR(180),
 titulo VARCHAR(220) NOT NULL,
 objetivo TEXT NOT NULL,
 inicio DATE,
 fin DATE,
 estado VARCHAR(26) NOT NULL DEFAULT 'REGISTRADA' CHECK(estado IN('REGISTRADA','EN_REVISION','APROBADA','EN_CURSO','INFORME_ENTREGADO','FINALIZADA','DEVUELTA')),
 informe_url VARCHAR(900),
 creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 actualizado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 CONSTRAINT practica_fechas CHECK(fin IS NULL OR inicio IS NULL OR fin>=inicio)
);
CREATE TABLE IF NOT EXISTS parcial_julian.practicas_seguimientos (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 practica_id BIGINT NOT NULL REFERENCES parcial_julian.practicas(id) ON DELETE RESTRICT,
 usuario_id BIGINT NOT NULL REFERENCES parcial_julian.usuarios(id),
 tipo VARCHAR(24) NOT NULL CHECK(tipo IN('AVANCE','RETROALIMENTACION','DECISION','INFORME')),
 detalle TEXT NOT NULL,
 evidencia_url VARCHAR(900),
 fecha TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_julian_practicas_estudiante ON parcial_julian.practicas(estudiante_id,estado);
CREATE INDEX IF NOT EXISTS idx_julian_practicas_tutor ON parcial_julian.practicas(tutor_id,estado);
CREATE INDEX IF NOT EXISTS idx_julian_practicas_seguimiento ON parcial_julian.practicas_seguimientos(practica_id,fecha);
